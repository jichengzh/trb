data = np.array([
    [27.016, 154.0000, 0.388,1 , 135.64],
    [38.921, 161.6400, 0.293,1 , 27.89],
    [29.571, 149.7450, 0.359,1 , 18.64],
    [29.537, 143.9160, 0.391,1 , 23.36],
    [35.598, 152.3550, 0.324,1 , 20.71],
    [38.921, 161.64,   0.293,1 , 557.89],
    [36.136, 141.82,   0.322,1 , 278.92],
    [30.950, 140.3597, 0.385,1 , 111.56],
], dtype=float)

df = pd.DataFrame(data, columns=['M1','M2','M3','E_bar','single_frame_energy'])

# ===== 线性权重（和=1）=====
w = np.array([0.68, 0.15, 0.17], dtype=float)

# ===== 各指标的尺度系数（不做归一化，直接按参数缩放）=====
# 你原代码里相当于：M2 / 5, M3 * 100
scales = np.array([1.0, 1/5, 50.0], dtype=float)

# ===== 加权求和（无归一化版）=====
metrics = df[['M1','M2','M3']].values
metrics_scaled = metrics * scales          # 直接按给定参数缩放
Q_linear = metrics_scaled @ w              # 线性加权求和

# ===== 计算 EER_AV（以 E_bar 为分母，不归一化）=====
eps = 1e-8
E = df['single_frame_energy'].values
EER_AV = Q_linear / (E + eps)

# ===== 输出 =====
out = df.copy()
out[['s_M1','s_M2','s_M3']] = metrics_scaled
out['Q_linear'] = Q_linear
out['EER_AV'] = EER_AV*100

pd.set_option('display.precision', 6)
print(out[['M1','M2','M3','E_bar','s_M1','s_M2','s_M3','Q_linear','EER_AV']])